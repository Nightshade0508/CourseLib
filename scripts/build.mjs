// Builds the deployable site into dist/:
//   public/        copied as is (page, runtime, vendor libraries, Kokoro voice model)
//   content/       library.json → dist/library.js, plus the selected docs/*.json
// By default only docs marked "public": true are included, so copyrighted course
// readings stay out of the public site. `--all` includes every doc (personal build).
import { existsSync } from 'node:fs';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const out = path.join(root, 'dist');
const all = process.argv.includes('--all');

const lib = JSON.parse(await readFile(path.join(root, 'content/library.json'), 'utf8'));
// non-public readings are not committed to the (public) repo; put their JSON in content/docs/ locally for a personal build
const docs = lib.docs.filter((d) => all || d.public)
  .filter((d) => existsSync(path.join(root, 'content/docs', d.id + '.json')) || console.warn(`skip ${d.id}: content/docs/${d.id}.json not found`))
  .map(({ public: _p, ...d }) => d);
const used = new Set(docs.map((d) => d.course));
const folders = lib.folders.filter((f) => all || used.has(f.id));
const sched = all || lib.includeSchedule ? lib.schedule : null;

await rm(out, { recursive: true, force: true });
await cp(path.join(root, 'public'), out, { recursive: true });
await mkdir(path.join(out, 'docs'), { recursive: true });
for (const d of docs) await cp(path.join(root, 'content/docs', d.id + '.json'), path.join(out, 'docs', d.id + '.json'));

const js = (o) => JSON.stringify(o).replace(/</g, '\\u003c');
await writeFile(path.join(out, 'library.js'),
  '// generated by scripts/build.mjs from content/library.json\n' +
  (sched ? `window.__SCHED__ = ${js(sched)};\n` : '') +
  `window.__FOLDERS__ = ${js(folders)};\nwindow.__DOCS__ = ${js(docs)};\n`);
await writeFile(path.join(out, '.nojekyll'), '');

console.log(`dist/ built: ${docs.length} docs, ${folders.length} folders${sched ? ', with schedule' : ''}${all ? ' (all content)' : ''}`);
